package generator

import (
	"bytes"
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"strconv"
	"strings"

	v3 "github.com/pb33f/libopenapi/datamodel/high/v3"
)

type eventData struct{ Name, Type, Description, Model, Package string }

func renderEvents(doc *v3.Document, params Params) error {
	events := []eventData{}
	if doc.Webhooks != nil {
		for eventType, path := range doc.Webhooks.FromOldest() {
			if path == nil || path.Post == nil {
				continue
			}
			op := path.Post
			var object struct {
				Ref string `yaml:"$ref"`
			}
			if op.Extensions == nil || op.Extensions.GetOrZero("x-object") == nil {
				return fmt.Errorf("event %s: missing x-object", eventType)
			}
			if err := op.Extensions.GetOrZero("x-object").Decode(&object); err != nil {
				return fmt.Errorf("event %s: decode object: %w", eventType, err)
			}
			model := strings.TrimPrefix(object.Ref, "#/components/schemas/")
			if model == object.Ref || doc.Components == nil || doc.Components.Schemas.GetOrZero(model) == nil || op.OperationId == "" {
				return fmt.Errorf("event %s: invalid object reference or operation ID", eventType)
			}
			description := strings.NewReplacer("&", "&amp;", "<", "&lt;", ">", "&gt;", "*/", "*&#47;").Replace(op.Description)
			events = append(events, eventData{pascalCase(strings.TrimSuffix(op.OperationId, "Webhook"), ""), strconv.Quote(eventType), description, pascalCase(model, ""), params.BasePackage})
		}
	}
	sort.Slice(events, func(i, j int) bool { return events[i].Type < events[j].Type })
	dir := filepath.Join(params.OutputDir, params.basePackagePath(), "events")
	if err := os.MkdirAll(dir, 0o755); err != nil {
		return fmt.Errorf("create events directory: %w", err)
	}
	entries, err := os.ReadDir(dir)
	if err != nil {
		return fmt.Errorf("read events directory: %w", err)
	}
	for _, entry := range entries {
		if entry.IsDir() || !strings.HasSuffix(entry.Name(), ".java") {
			continue
		}
		path := filepath.Join(dir, entry.Name())
		content, err := os.ReadFile(path)
		if err != nil {
			return fmt.Errorf("read generated event: %w", err)
		}
		if bytes.HasPrefix(content, []byte("// Code generated by sumup-java/codegen. DO NOT EDIT.")) {
			if err := os.Remove(path); err != nil {
				return fmt.Errorf("remove generated event: %w", err)
			}
		}
	}
	write := func(name, templateName string, data any) error {
		tmpl, err := loadTemplate(templateName)
		if err != nil {
			return err
		}
		var output bytes.Buffer
		if err := tmpl.Execute(&output, data); err != nil {
			return fmt.Errorf("render event %s: %w", name, err)
		}
		if err := os.WriteFile(filepath.Join(dir, name+".java"), output.Bytes(), 0o644); err != nil {
			return fmt.Errorf("write event %s: %w", name, err)
		}
		return nil
	}
	for _, event := range events {
		if err := write(event.Name+"Event", "event.tmpl", event); err != nil {
			return err
		}
	}
	data := struct {
		Package string
		Events  []eventData
		Async   bool
		Class   string
	}{params.BasePackage, events, false, "EventsHandler"}
	if err := write("EventNotification", "event_notification.tmpl", data); err != nil {
		return err
	}
	if err := write(data.Class, "events_handler.tmpl", data); err != nil {
		return err
	}
	data.Async = true
	data.Class = "AsyncEventsHandler"
	return write(data.Class, "events_handler.tmpl", data)
}
